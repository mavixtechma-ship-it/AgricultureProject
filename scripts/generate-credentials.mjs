// Generates the two demo accounts (admin, viewer) with random 14-char passwords.
// Writes:
//   - src/app/core/auth/auth.config.ts  → ONLY salted PBKDF2-SHA256 hashes (safe to commit)
//   - CREDENTIALS.md                    → plaintext passwords (git-ignored, never commit)
// Usage: npm run gen:credentials   (re-running rotates both passwords)
import { pbkdf2Sync, randomBytes, randomInt } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ITERATIONS = 310000;
const KEY_BYTES = 32;

const UPPER = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
const LOWER = 'abcdefghijkmnopqrstuvwxyz';
const DIGIT = '23456789';
const SYMBOL = '!@#%*-_+=?';
const ALL = UPPER + LOWER + DIGIT + SYMBOL;

function password(length = 14) {
  const pick = (set) => set[randomInt(set.length)];
  const chars = [pick(UPPER), pick(LOWER), pick(DIGIT), pick(SYMBOL)];
  while (chars.length < length) chars.push(pick(ALL));
  for (let i = chars.length - 1; i > 0; i--) {
    const j = randomInt(i + 1);
    [chars[i], chars[j]] = [chars[j], chars[i]];
  }
  return chars.join('');
}

const accounts = [
  { username: 'admin', role: 'admin', displayName: 'Administrator' },
  { username: 'viewer', role: 'viewer', displayName: 'Guest viewer' },
].map((a) => {
  const pw = password();
  const salt = randomBytes(16);
  const hash = pbkdf2Sync(pw, salt, ITERATIONS, KEY_BYTES, 'sha256');
  return { ...a, password: pw, salt: salt.toString('base64'), hash: hash.toString('base64') };
});

const ts = `// AUTO-GENERATED by scripts/generate-credentials.mjs — do not edit by hand.
// Contains only salted PBKDF2-SHA256 hashes. Plaintext passwords live in the git-ignored CREDENTIALS.md.
// NOTE: this is a client-side demo access gate, not real security (there is no backend).
import { DemoAccount } from './auth.models';

export const PBKDF2_ITERATIONS = ${ITERATIONS};

export const DEMO_ACCOUNTS: readonly DemoAccount[] = [
${accounts
  .map(
    (a) => `  {
    username: '${a.username}',
    role: '${a.role}',
    displayName: '${a.displayName}',
    salt: '${a.salt}',
    hash: '${a.hash}',
  },`
  )
  .join('\n')}
];
`;
writeFileSync(join(root, 'src/app/core/auth/auth.config.ts'), ts);

const md = `# CREDENTIALS — AgriSense demo (DO NOT COMMIT)

This file is git-ignored. Only PBKDF2-SHA256 hashes (310,000 iterations, 16-byte random salt) are stored in the source
(\`src/app/core/auth/auth.config.ts\`). Rotate with \`npm run gen:credentials\`.

| Username | Password | Role | Access |
|---|---|---|---|
${accounts.map((a) => `| \`${a.username}\` | \`${a.password}\` | ${a.role} | ${a.role === 'admin' ? 'Full access: toggle pump / fertilizer doser, acknowledge alerts' : 'Read-only: dashboards and alerts, controls disabled'} |`).join('\n')}
`;
writeFileSync(join(root, 'CREDENTIALS.md'), md);
console.log('Generated credentials for:', accounts.map((a) => a.username).join(', '));
